<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

class ClassSchedule extends Model
{
    use HasFactory;

    protected $fillable = [
        'class_id', 'tutor_id', 'title', 'description', 'start_time', 'end_time',
        'meeting_link', 'meeting_platform', 'status', 'completed_at', 'completed_by', 'recording_url',
        'recurrence_rule', 'recurrence_until', 'recurrence_group',
    ];

    protected $casts = [
        'start_time' => 'datetime',
        'end_time' => 'datetime',
        'completed_at' => 'datetime',
        'recurrence_until' => 'date',
    ];

    public function class()
    {
        return $this->belongsTo(Classes::class, 'class_id');
    }

    public function tutor()
    {
        return $this->belongsTo(Tutor::class);
    }

    public function attendance()
    {
        return $this->hasMany(Attendance::class);
    }

    /** Who ticked this session as completed (administrator, CEO or the tutor). */
    public function completedBy()
    {
        return $this->belongsTo(User::class, 'completed_by');
    }

    public function isCompleted(): bool
    {
        return $this->status === 'completed';
    }

    /** A session can only be ticked once its scheduled end time has passed. */
    public function hasEnded(): bool
    {
        return $this->end_time !== null && now()->greaterThanOrEqualTo($this->end_time);
    }

    /** Sessions that count towards a tutor's monthly teaching report. */
    public function scopeCompleted($query)
    {
        return $query->where('status', 'completed');
    }

    /** True when this session was generated by a weekly repeat. */
    public function isRecurring(): bool
    {
        return $this->recurrence_rule === 'weekly';
    }

    /** Day and time this series repeats, e.g. "Every Monday, 4:00 pm". */
    public function repeatLabel(): string
    {
        if (! $this->isRecurring()) {
            return 'One-off';
        }

        return 'Every ' . $this->start_time->format('l') . ', ' . $this->start_time->format('g:i a');
    }

    /**
     * Every day and time in this session's series, e.g.
     * "Mon 10:00 am, Wed 2:00 pm, Fri 6:00 pm" — a weekly series can run on
     * several days at different times.
     */
    public function seriesLabel(): string
    {
        if (! $this->isRecurring() || ! $this->recurrence_group) {
            return 'One-off';
        }

        // One query per group, not per row on the schedules list.
        static $labels = [];

        $group = $this->recurrence_group;

        if (! array_key_exists($group, $labels)) {
            $labels[$group] = static::where('recurrence_group', $group)
                ->orderBy('start_time')
                ->get(['start_time'])
                ->map(function (self $session) {
                    return $session->start_time->format('D g:i a');
                })
                ->unique()
                ->values()
                ->implode(', ');
        }

        return 'Every ' . $labels[$group];
    }

    /** Tailwind label for the platform stored on the row. */
    public function platformLabel(): string
    {
        $labels = [
            'google_meet' => 'Google Meet',
            'zoom' => 'Zoom',
            'jitsi' => 'Automatic video room',
        ];

        return $labels[$this->meeting_platform] ?? 'No platform';
    }
}
